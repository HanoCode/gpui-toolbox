//! Nginx 配置文本渲染（替代源仓的 `templates.rs` + `nginx.conf.tera`）。
//!
//! 输出结构与模板逐行对齐：指令顺序、缩进、分号、条件分支都一样。
//! 唯一差别见模块头（空行不再留缩进空格）。
//!
//! 模板里三句中文注释由 [`Comments`] 传入 —— 它们是**产物的一部分**，
//! 但内核不产中文。

use super::config::NginxConfig;

/// 产物里的三句中文注释（插件层按当前语言给）。
#[derive(Debug, Clone, Copy)]
pub struct Comments<'a> {
    /// 对应模板 `# 客户端最大请求体大小`。
    pub client_max_body_size: &'a str,
    /// 对应模板 `# SSL 配置`。
    pub ssl: &'a str,
    /// 对应模板 `# 错误页面`。
    pub error_pages: &'a str,
}

impl Comments<'_> {
    /// 不想传注释时的空实现（测试与「只要配置文本」的调用方用）。
    pub fn empty() -> &'static Comments<'static> {
        &Comments {
            client_max_body_size: "",
            ssl: "",
            error_pages: "",
        }
    }
}

/// 渲染完整 `nginx.conf`。
pub fn render(config: &NginxConfig, comments: &Comments<'_>) -> String {
    let mut out = String::with_capacity(4 * 1024);

    out.push_str("# Generated by nginxconfig.io\n");
    out.push_str("user nobody;\n");
    line(
        &mut out,
        0,
        &format!("worker_processes {};", config.advanced.worker_processes),
    );
    out.push('\n');
    out.push_str("#error_log logs/error.log;\n");
    out.push_str("#error_log logs/error.log notice;\n");
    out.push_str("#error_log logs/error.log info;\n\n");
    out.push_str("#pid logs/nginx.pid;\n\n");

    out.push_str("events {\n");
    line(
        &mut out,
        1,
        &format!("worker_connections {};", config.advanced.worker_connections),
    );
    extra(&mut out, 1, &config.advanced.extra_events_directives);
    out.push_str("}\n\n");

    out.push_str("http {\n");
    line(&mut out, 1, "include mime.types;");
    line(&mut out, 1, "default_type application/octet-stream;");
    out.push('\n');
    comment(&mut out, 1, comments.client_max_body_size);
    line(
        &mut out,
        1,
        &format!(
            "client_max_body_size {};",
            config.performance.client_max_body_size
        ),
    );
    out.push('\n');
    line(&mut out, 1, "#access_log logs/access.log main;");
    out.push('\n');
    line(&mut out, 1, "sendfile on;");
    line(&mut out, 1, "#tcp_nopush on;");
    out.push('\n');
    line(
        &mut out,
        1,
        &format!(
            "keepalive_timeout {};",
            config.performance.keepalive_timeout
        ),
    );

    if config.performance.gzip {
        out.push('\n');
        line(&mut out, 1, "gzip on;");
        line(&mut out, 1, "gzip_vary on;");
        line(&mut out, 1, "gzip_proxied any;");
        line(
            &mut out,
            1,
            &format!("gzip_comp_level {};", config.performance.gzip_comp_level),
        );
        line(
            &mut out,
            1,
            &format!("gzip_min_length {};", config.performance.gzip_min_length),
        );
        line(
            &mut out,
            1,
            &format!("gzip_types {};", config.performance.gzip_types.join(" ")),
        );
    }

    if !config.security.server_tokens {
        out.push('\n');
        line(&mut out, 1, "server_tokens off;");
    }

    if !config.advanced.extra_http_directives.trim().is_empty() {
        out.push('\n');
        extra(&mut out, 1, &config.advanced.extra_http_directives);
    }

    for upstream in &config.upstreams {
        out.push('\n');
        line(&mut out, 1, &format!("upstream {} {{", upstream.name));
        for server in &upstream.servers {
            let backup = if server.backup { " backup" } else { "" };
            line(
                &mut out,
                2,
                &format!(
                    "server {} weight={}{backup};",
                    server.address, server.weight
                ),
            );
        }
        line(&mut out, 2, &format!("keepalive {};", upstream.keepalive));
        line(&mut out, 1, "}");
    }

    if config.ssl.enabled {
        out.push('\n');
        comment(&mut out, 1, comments.ssl);
        line(&mut out, 1, "ssl_session_timeout 1d;");
        line(&mut out, 1, "ssl_session_cache shared:SSL:10m;");
        line(&mut out, 1, "ssl_session_tickets off;");
        line(
            &mut out,
            1,
            &format!("ssl_protocols {};", config.ssl.protocols.join(" ")),
        );
        line(&mut out, 1, &format!("ssl_ciphers {};", config.ssl.ciphers));
        line(
            &mut out,
            1,
            &format!(
                "ssl_prefer_server_ciphers {};",
                on_off(config.ssl.prefer_server_ciphers)
            ),
        );
    }

    out.push('\n');
    line(&mut out, 1, "server {");
    let listen = match config.ssl.enabled {
        true => format!("listen {} ssl;", config.server.listen_port),
        false => format!("listen {};", config.server.listen_port),
    };
    line(&mut out, 2, &listen);
    line(
        &mut out,
        2,
        &format!("server_name {};", config.server.server_name),
    );
    out.push('\n');
    line(&mut out, 2, &format!("charset {};", config.server.charset));

    out.push('\n');
    if config.ssl.enabled {
        line(
            &mut out,
            2,
            &format!("ssl_certificate {};", config.ssl.certificate_path),
        );
        line(
            &mut out,
            2,
            &format!("ssl_certificate_key {};", config.ssl.certificate_key_path),
        );
        if !config.ssl.trusted_certificate_path.is_empty() {
            line(
                &mut out,
                2,
                &format!(
                    "ssl_trusted_certificate {};",
                    config.ssl.trusted_certificate_path
                ),
            );
        }
        if config.security.hsts {
            let subdomains = if config.security.hsts_include_subdomains {
                "; includeSubDomains"
            } else {
                ""
            };
            line(
                &mut out,
                2,
                &format!(
                    "add_header Strict-Transport-Security \"max-age={}{subdomains}\" always;",
                    config.security.hsts_max_age
                ),
            );
        }
    }

    if !config.security.x_frame_options.is_empty() {
        line(
            &mut out,
            2,
            &format!(
                "add_header X-Frame-Options \"{}\" always;",
                config.security.x_frame_options
            ),
        );
    }
    if config.security.x_content_type_options {
        line(
            &mut out,
            2,
            "add_header X-Content-Type-Options \"nosniff\" always;",
        );
    }
    if !config.security.x_xss_protection.is_empty() {
        line(
            &mut out,
            2,
            &format!(
                "add_header X-XSS-Protection \"{}\" always;",
                config.security.x_xss_protection
            ),
        );
    }
    if !config.security.referrer_policy.is_empty() {
        line(
            &mut out,
            2,
            &format!(
                "add_header Referrer-Policy \"{}\" always;",
                config.security.referrer_policy
            ),
        );
    }

    out.push('\n');
    line(&mut out, 2, "#access_log logs/host.access.log main;");

    for location in &config.locations {
        out.push('\n');
        line(&mut out, 2, &format!("location {} {{", location.path));
        match location.location_type.as_str() {
            "proxy" => {
                line(
                    &mut out,
                    3,
                    &format!("proxy_buffers {};", location.proxy_buffers),
                );
                line(
                    &mut out,
                    3,
                    &format!("proxy_buffer_size {};", location.proxy_buffer_size),
                );
                line(
                    &mut out,
                    3,
                    &format!("proxy_read_timeout {};", location.proxy_read_timeout),
                );
                line(
                    &mut out,
                    3,
                    &format!("proxy_connect_timeout {};", location.proxy_connect_timeout),
                );
                // 模板就是 `proxy_pass {{ target }}/` —— 末尾这一斜杠是它加的。
                line(&mut out, 3, &format!("proxy_pass {}/;", location.target));
            }
            "alias" => {
                line(&mut out, 3, &format!("alias {};", location.target));
                line(
                    &mut out,
                    3,
                    &format!("autoindex {};", on_off(location.autoindex)),
                );
            }
            "root" => {
                line(&mut out, 3, &format!("root {};", location.target));
                line(
                    &mut out,
                    3,
                    &format!("autoindex {};", on_off(location.autoindex)),
                );
            }
            // 未知类型：模板里 `{% if %}` 全不命中 ⇒ 只剩额外指令，这里同语义。
            _ => {}
        }
        extra(&mut out, 3, &location.extra_directives);
        line(&mut out, 2, "}");
    }

    if !config.error_pages.is_empty() {
        out.push('\n');
        comment(&mut out, 2, comments.error_pages);
        for page in &config.error_pages {
            line(
                &mut out,
                2,
                &format!("error_page {} {};", page.code, page.uri),
            );
        }
    }

    out.push('\n');
    line(&mut out, 2, "location = /50x.html {");
    line(&mut out, 3, "root html;");
    line(&mut out, 2, "}");
    line(&mut out, 1, "}");
    out.push_str("}\n");
    out
}

fn on_off(flag: bool) -> &'static str {
    if flag { "on" } else { "off" }
}

/// 一行指令，按层缩进（4 空格一层）。
fn line(out: &mut String, depth: usize, text: &str) {
    for _ in 0..depth {
        out.push_str("    ");
    }
    out.push_str(text);
    out.push('\n');
}

/// 注释行；空注释直接跳过（不输出一行孤零零的 `#`）。
fn comment(out: &mut String, depth: usize, text: &str) {
    if text.trim().is_empty() {
        return;
    }
    line(out, depth, &format!("# {}", text.trim()));
}

/// 用户自定义指令块：按当前层级**统一缩进**，块内部的相对缩进保留。
///
/// 源仓是把 `extra_directives` 原样贴进模板（Tera 只给第一行加缩进），于是
/// 「第一行 12 空格、后面几行 8 空格」的错位在产物里随处可见。这里改成：
/// 取后续行的**公共缩进**当基准，逐行重排到 `depth`，块内嵌套（`if {}` 之类）
/// 因为相对差还在而保持不变。
fn extra(out: &mut String, depth: usize, text: &str) {
    let trimmed = text.trim_end();
    if trimmed.trim().is_empty() {
        return;
    }
    let lines: Vec<&str> = trimmed.lines().collect();
    // 基准只由**后续行**决定：第一行的位置由调用点的 `depth` 说了算。
    let base = lines
        .iter()
        .skip(1)
        .filter(|line| !line.trim().is_empty())
        .map(|line| line.len() - line.trim_start().len())
        .min()
        .unwrap_or(0);
    for (index, raw) in lines.iter().enumerate() {
        if raw.trim().is_empty() {
            out.push('\n');
            continue;
        }
        for _ in 0..depth {
            out.push_str("    ");
        }
        let relative = match index {
            0 => 0,
            _ => (raw.len() - raw.trim_start().len()).saturating_sub(base),
        };
        for _ in 0..relative {
            out.push(' ');
        }
        out.push_str(raw.trim_start());
        out.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::nginx::config::{LocationConfig, UpstreamServer};

    fn comments() -> Comments<'static> {
        Comments {
            client_max_body_size: "max body",
            ssl: "SSL",
            error_pages: "error pages",
        }
    }

    #[test]
    fn default_config_renders_the_expected_skeleton() {
        let text = render(&NginxConfig::default(), &comments());
        assert!(
            text.starts_with(
                "# Generated by nginxconfig.io\nuser nobody;\nworker_processes auto;\n"
            )
        );
        assert!(text.contains("events {\n    worker_connections 1024;\n}\n"));
        assert!(text.contains("    gzip on;\n"));
        assert!(text.contains("    server_tokens off;\n"));
        assert!(text.contains("    upstream backend {\n        server 127.0.0.1:8080 weight=1;\n        keepalive 32;\n    }\n"));
        assert!(text.contains("\n    server {\n        listen 80;\n        server_name _;\n"));
        assert!(text.contains(
            "        location / {\n            root /var/www/html;\n            autoindex off;\n        }\n"
        ));
        // 末尾依次关掉：server 块、http 块。
        assert!(
            text.trim_end()
                .ends_with("location = /50x.html {\n            root html;\n        }\n    }\n}")
        );
        // 缩进全部是 4 的倍数，且没有制表符。
        assert!(!text.contains('\t'));
    }

    #[test]
    fn ssl_block_adds_listen_ssl_and_hsts() {
        let mut config = NginxConfig::default();
        config.ssl.enabled = true;
        config.security.hsts = true;
        let text = render(&config, &comments());
        assert!(text.contains("listen 80 ssl;"));
        assert!(text.contains("ssl_certificate /etc/nginx/ssl/cert.pem;"));
        assert!(text.contains("ssl_trusted_certificate /etc/nginx/ssl/chain.pem;"));
        assert!(text.contains(
            "add_header Strict-Transport-Security \"max-age=31536000; includeSubDomains\" always;"
        ));
    }

    #[test]
    fn proxy_location_appends_the_trailing_slash() {
        let config = NginxConfig {
            locations: vec![LocationConfig {
                path: "/api/".to_owned(),
                location_type: "proxy".to_owned(),
                target: "http://backend".to_owned(),
                ..LocationConfig::default()
            }],
            ..NginxConfig::default()
        };
        let text = render(&config, &comments());
        assert!(text.contains("proxy_pass http://backend/;"), "{text}");
    }

    #[test]
    fn backup_servers_are_marked() {
        let mut config = NginxConfig::default();
        config.upstreams[0].servers = vec![UpstreamServer {
            address: "10.0.0.2:8080".to_owned(),
            weight: "3".to_owned(),
            backup: true,
        }];
        let text = render(&config, &comments());
        assert!(text.contains("server 10.0.0.2:8080 weight=3 backup;"));
    }

    #[test]
    fn extra_directives_are_realigned_but_keep_relative_nesting() {
        let config = NginxConfig {
            locations: vec![LocationConfig {
                extra_directives: "proxy_set_header Host $host;\n    proxy_set_header X-Real-IP $remote_addr;\n    if ($bad) {\n        return 444;\n    }".to_owned(),
                ..LocationConfig::default()
            }],
            ..NginxConfig::default()
        };
        let text = render(&config, Comments::empty());
        // location 体在 depth 3（12 空格）；块内的 `if` 多出的 4 空格要保留。
        assert!(text.contains(
            "            proxy_set_header Host $host;\n            proxy_set_header X-Real-IP $remote_addr;\n            if ($bad) {\n                return 444;\n            }\n"
        ), "{text}");
    }

    #[test]
    fn empty_comments_render_nothing_and_extra_directives_are_kept() {
        let mut config = NginxConfig::default();
        config.advanced.extra_http_directives =
            "    log_format main '$remote_addr';\n    access_log off;".to_owned();
        let text = render(&config, Comments::empty());
        assert!(!text.contains("# \n"), "空注释不该留孤零零的 #");
        assert!(text.contains("    log_format main '$remote_addr';\n    access_log off;\n"));
    }
}
